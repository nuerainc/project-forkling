from buggy import is_valid_sudoku


VALID_BOARD = [
    ['5', '3', '.', '.', '7', '.', '.', '.', '.'],
    ['6', '.', '.', '1', '9', '5', '.', '.', '.'],
    ['.', '9', '8', '.', '.', '.', '.', '6', '.'],
    ['8', '.', '.', '.', '6', '.', '.', '.', '3'],
    ['4', '.', '.', '8', '.', '3', '.', '.', '1'],
    ['7', '.', '.', '.', '2', '.', '.', '.', '6'],
    ['.', '6', '.', '.', '.', '.', '2', '8', '.'],
    ['.', '.', '.', '4', '1', '9', '.', '.', '5'],
    ['.', '.', '.', '.', '8', '.', '.', '7', '9'],
]


def test_valid_classic_board():
    assert is_valid_sudoku(VALID_BOARD) is True


def test_subgrid_violation_no_row_or_col_conflict():
    # 5 appears at (0,0) and (2,2) — same top-left 3x3 box, different row
    # and different column. Rows and columns are still unique, but the box
    # is not.
    board = [
        ['5', '1', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '2', '.', '.', '.', '.', '.', '.'],
        ['3', '.', '5', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
    ]
    assert is_valid_sudoku(board) is False


def test_simple_two_row_duplicates():
    # Two 1s in row 0, distinct columns.
    board = [
        ['1', '.', '.', '.', '.', '.', '.', '.', '1'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
        ['.', '.', '.', '.', '.', '.', '.', '.', '.'],
    ]
    assert is_valid_sudoku(board) is False
