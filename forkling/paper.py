"""forkland drafts its own paper sections.

Reads the diary, capability ledger, graveyard, and fitness snapshots,
then writes structured markdown into ``paper/paper.md``. Each call
either regenerates the whole document or appends a new section.

The agent's own paper-writing is a form of *self-publication*: every
milestone the agent has shipped becomes evidence in the paper, and
the paper itself becomes a research artifact that humans can submit
to arXiv or to a venue's open-review track.

This module is deliberately template-driven: the agent's job is to
fill in numbers and pull milestones, not to invent prose. The template
is what a careful human co-author would write; the agent just plugs
in the latest data.
"""

from __future__ import annotations

import json
import time
from collections import Counter
from pathlib import Path

from .capability import CapabilityLedger
from .diary import Diary
from .evolution import Evolution, format_fitness_history
from .graveyard import Graveyard


