def render(memory_dir: str | Path = "~/.forkling",
           fitness_history: list | None = None) -> str:
    """Render the full paper from current state.

    fitness_history is optional; if absent, only the current fitness is shown.
    """
    state_dir = Path(memory_dir).expanduser()
    ledger = CapabilityLedger(state_dir / "capabilities.jsonl")
    diary = Diary(state_dir / "diary.jsonl")
    graveyard = Graveyard(state_dir / "graveyard.jsonl")
    evo = Evolution(ledger, graveyard, state_dir)
    fit = evo.fitness()

    capabilities = len(ledger.entries())
    distinct_actions = len(ledger.distinct_actions())
    graveyard_total = len(graveyard.entries())
    milestones = len(diary.milestones())

    # Top rejection reasons.
    stats = graveyard.stats()
    by_reason = stats.get("by_reason", {})
    if by_reason:
        top = sorted(by_reason.items(), key=lambda kv: kv[1], reverse=True)[:5]
        lines = [f"  - {reason}: {n}" for reason, n in top]
        graveyard_reasons = "\n".join(lines)
    else:
        graveyard_reasons = "  (no rejections yet)"

    # Milestones block.
    ms = diary.milestones()
    if ms:
        recent = ms[-10:]
        lines = []
        for e in recent:
            ts = time.strftime("%Y-%m-%d", time.localtime(e.get("ts", 0)))
            lines.append(f"  - {ts}: {e.get('content', '')[:120]}")
        format_milestones = "\n".join(lines)
    else:
        format_milestones = "  (no milestones yet)"

    # Fitness block — single point in time if no history given.
    if fitness_history:
        fh = format_fitness_history(fitness_history)
    else:
        fh = f"  current  smartness={fit.smartness:.3f}  skill={fit.skill:.3f}  total={fit.total:.3f}"

    return PAPER_TEMPLATE.format(
        generated_at=time.strftime("%Y-%m-%d %H:%M:%S"),
        milestones=milestones,
        capabilities=capabilities,
        graveyard_total=graveyard_total,
        distinct_actions=distinct_actions,
        graveyard_reasons=graveyard_reasons,
        format_fitness_history_placeholder=fh,
        format_milestones_placeholder=format_milestones,
    )


def update(memory_dir: str | Path = "~/.forkling",
           paper_path: str | Path = "paper/paper.md") -> str:
    """Render the paper and write it to disk. Returns the path written."""
    text = render(memory_dir)
    p = Path(paper_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return str(p)


def append_status(memory_dir: str | Path = "~/.forkling",
                  paper_path: str | Path = "paper/paper.md") -> str:
    """Append a single-paragraph status update to the paper (keeps history)."""
    state_dir = Path(memory_dir).expanduser()
    ledger = CapabilityLedger(state_dir / "capabilities.jsonl")
    graveyard = Graveyard(state_dir / "graveyard.jsonl")
    diary = Diary(state_dir / "diary.jsonl")
    fit = Evolution(ledger, graveyard, state_dir).fitness()

    note = (
        f"\n\n---\n\n"
        f"## Update at {time.strftime('%Y-%m-%d %H:%M:%S')}\n\n"
        f"- capabilities: {len(ledger.entries())}\n"
        f"- rejected patches: {len(graveyard.entries())}\n"
        f"- diary milestones: {len(diary.milestones())}\n"
        f"- fitness: smartness={fit.smartness:.3f}, skill={fit.skill:.3f}, "
        f"total={fit.total:.3f}\n"
    )
    p = Path(paper_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a", encoding="utf-8") as f:
        f.write(note)
    return str(p)